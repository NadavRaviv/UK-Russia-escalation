// Regenerates options-data.js from the live tracker page so the four redesign
// options always render the same 40 rows, bands and domains as the real site.
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import vm from "node:vm";

const root = new URL("../", import.meta.url);
const html = readFileSync(fileURLToPath(new URL("uk-russia-merged-timeline.html", root)), "utf8");

const grab = (name) => {
  const start = html.indexOf(`const ${name} = `);
  const end = html.indexOf("\n];", start);
  const open = name === "T" ? html.indexOf("\n};", start) + 3 : end + 3;
  return vm.runInNewContext(`(${html.slice(start + `const ${name} = `.length, open).replace(/;\s*$/, "")})`);
};

const T = grab("T");
const EVENTS = grab("EVENTS");

const pick = (t) => ({
  eyebrow: t.eyebrow,
  title: t.title,
  standfirst: t.standfirst,
  bands: t.bands,
  domains: t.domains,
  months: t.months,
  tlTitle: t.tlTitle,
  tlCount: t.tlCount,
  footLine: t.footLine,
  askTitle: t.askTitle,
  askNote: t.askNote,
  askPlaceholder: t.askPlaceholder,
  askSubmit: t.askSubmit,
  methodBtn: t.methodBtn,
  whyBtn: t.whyBtn,
  whyClose: t.whyClose,
  dangerHigh: t.dangerHigh,
  dangerLow: t.dangerLow,
  impactLow: t.impactLow,
  impactHigh: t.impactHigh,
  selDangerL: t.selDangerL,
  selImpactL: t.selImpactL,
  selBandL: t.selBandL,
  povAll: t.povAll,
  sides: t.sides,
  s1: t.s1,
  s2: t.s2,
  s3: t.s3,
  s4: t.s4,
  unit: t.unit,
  p0: t.p0,
  p1: t.p1,
  k1: t.k1.replace(/<[^>]+>/g, ""),
  k2: t.k2.replace(/<[^>]+>/g, ""),
});

const events = EVENTS.map((e, i) => ({
  id: i,
  date: e.date,
  approx: !!e.approx,
  side: e.side,
  direct: e.rag === "r",
  band: e.band,
  domain: e.domain,
  danger: e.danger,
  impact: e.impact,
  sources: e.sources,
  en: e.en,
  he: e.he,
}));

const out = `/* Generated by build-data.mjs from uk-russia-merged-timeline.html. Do not edit by hand. */
window.UKRU = ${JSON.stringify({ events, ui: { en: pick(T.en), he: pick(T.he) } })};
`;
writeFileSync(fileURLToPath(new URL("redesign-options/options-data.js", root)), out);
console.log(`wrote ${events.length} events, ${(out.length / 1024).toFixed(1)} KB`);
